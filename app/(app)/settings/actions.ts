"use server";

import { z } from "zod";

import { unverifiedTotpFactors, verifiedTotpFactor } from "@/lib/auth/assurance";
import { authError, logAuthError, mapAuthError, type AuthActionResult } from "@/lib/auth/errors";
import { createSupabaseServerClient } from "@/lib/auth/server";
import { getSessionStatus } from "@/lib/auth/session";
import {
  cancelTwoFactorSetupSchema,
  confirmTwoFactorSetupSchema,
  disableTwoFactorSchema,
} from "@/lib/validation/auth";

// Turning authenticator-app 2FA on and off (unit 1.4). Each action is a public endpoint: it
// validates its input, requires a session that has finished 2FA, and acts only on a factor that
// Supabase lists for this user. Codes, setup keys, QR codes and factor IDs are never logged. See
// context/feature-specs/1.4-authenticator-app-2fa.md, Flows.

export type SettingsActionResult<T> = { data: T } | AuthActionResult;

export interface TwoFactorSetup {
  factorId: string;
  // A data: URL of Supabase's QR code SVG, for an <img>.
  qrCode: string;
  // The setup key, for "Can't scan it?".
  secret: string;
}

const FRIENDLY_NAME = "Authenticator app";
const ISSUER = "FinTrack";

type Supabase = Awaited<ReturnType<typeof createSupabaseServerClient>>;

async function signedInClient(): Promise<Supabase | AuthActionResult> {
  const { state } = await getSessionStatus();
  if (state === "signed-out") {
    return authError("NOT_SIGNED_IN");
  }
  if (state === "needs-2fa") {
    return authError("TWO_FACTOR_REQUIRED");
  }
  return createSupabaseServerClient();
}

function isFailure(value: Supabase | AuthActionResult): value is AuthActionResult {
  return "error" in value;
}

// The user, with its factors, straight from Supabase (never the session cookie's copy).
async function currentUser(supabase: Supabase, action: string) {
  const { data, error } = await supabase.auth.getUser();
  if (error || !data.user) {
    if (error) {
      logAuthError(action, error);
    }
    return null;
  }
  return data.user;
}

// A wrong or expired code is the user's typo and isn't logged; anything else is.
function codeFailure(action: string, error: unknown): AuthActionResult {
  const code = mapAuthError(error);
  if (code !== "INVALID_CODE") {
    logAuthError(action, error);
  }
  return authError(code === "INVALID_CODE" || code === "RATE_LIMITED" ? code : "AUTH_FAILED");
}

// Supabase returns the QR code as `data:image/svg+xml;utf-8,<?xml …?><!-- Generated by SVGo --><svg …>`,
// unescaped. The SVG is re-encoded so characters such as `#` can't cut the URL short. It is shown
// in an <img>, which never runs scripts.
const SVG_START = /^(?:<\?xml[^>]*\?>|<!--[\s\S]*?-->|\s)*<svg[\s>]/;

function qrCodeUrl(value: string): string | null {
  const svg = value.slice(value.indexOf(",") + 1).trim();
  if (!value.startsWith("data:image/svg+xml") || !SVG_START.test(svg)) {
    return null;
  }
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

export async function startTwoFactorSetup(): Promise<SettingsActionResult<TwoFactorSetup>> {
  const supabase = await signedInClient();
  if (isFailure(supabase)) {
    return supabase;
  }
  const user = await currentUser(supabase, "startTwoFactorSetup");
  if (!user) {
    return authError("AUTH_FAILED");
  }
  if (verifiedTotpFactor(user)) {
    return authError("TWO_FACTOR_ALREADY_ON");
  }

  // An abandoned setup leaves an unverified factor, whose name would clash with the new one.
  for (const factor of unverifiedTotpFactors(user)) {
    const { error } = await supabase.auth.mfa.unenroll({ factorId: factor.id });
    if (error) {
      logAuthError("startTwoFactorSetup", error);
      return authError("AUTH_FAILED");
    }
  }

  const { data, error } = await supabase.auth.mfa.enroll({
    factorType: "totp",
    friendlyName: FRIENDLY_NAME,
    issuer: ISSUER,
  });
  if (error) {
    logAuthError("startTwoFactorSetup", error);
    const code = mapAuthError(error);
    return authError(code === "TWO_FACTOR_ALREADY_ON" || code === "RATE_LIMITED" ? code : "AUTH_FAILED");
  }
  const qrCode = qrCodeUrl(data.totp.qr_code);
  if (!qrCode || !data.totp.secret) {
    // Fixed text only: the response holds the setup key.
    console.error("[auth] startTwoFactorSetup failed: UnexpectedEnrollResponse (none)");
    return authError("AUTH_FAILED");
  }
  return { data: { factorId: data.id, qrCode, secret: data.totp.secret } };
}

export async function confirmTwoFactorSetup(input: unknown): Promise<SettingsActionResult<{ enabled: true }>> {
  const parsed = confirmTwoFactorSetupSchema.safeParse(input);
  if (!parsed.success) {
    return authError("INVALID_CODE", z.flattenError(parsed.error).fieldErrors);
  }
  const supabase = await signedInClient();
  if (isFailure(supabase)) {
    return supabase;
  }
  const user = await currentUser(supabase, "confirmTwoFactorSetup");
  // Only this user's own setup that hasn't been confirmed yet.
  if (!user || !unverifiedTotpFactors(user).some((factor) => factor.id === parsed.data.factorId)) {
    return authError("AUTH_FAILED");
  }

  // The first correct code verifies the factor and raises this session to aal2. Supabase signs out
  // the user's other sessions.
  const { error } = await supabase.auth.mfa.challengeAndVerify({
    factorId: parsed.data.factorId,
    code: parsed.data.code,
  });
  if (error) {
    return codeFailure("confirmTwoFactorSetup", error);
  }
  return { data: { enabled: true } };
}

export async function cancelTwoFactorSetup(input: unknown): Promise<SettingsActionResult<{ cancelled: true }>> {
  const parsed = cancelTwoFactorSetupSchema.safeParse(input);
  if (!parsed.success) {
    return authError("AUTH_FAILED");
  }
  const supabase = await signedInClient();
  if (isFailure(supabase)) {
    return supabase;
  }
  const user = await currentUser(supabase, "cancelTwoFactorSetup");
  if (!user || !unverifiedTotpFactors(user).some((factor) => factor.id === parsed.data.factorId)) {
    return authError("AUTH_FAILED");
  }
  const { error } = await supabase.auth.mfa.unenroll({ factorId: parsed.data.factorId });
  if (error) {
    logAuthError("cancelTwoFactorSetup", error);
    return authError("AUTH_FAILED");
  }
  return { data: { cancelled: true } };
}

export async function disableTwoFactor(input: unknown): Promise<SettingsActionResult<{ disabled: true }>> {
  const parsed = disableTwoFactorSchema.safeParse(input);
  if (!parsed.success) {
    return authError("INVALID_CODE", z.flattenError(parsed.error).fieldErrors);
  }
  const supabase = await signedInClient();
  if (isFailure(supabase)) {
    return supabase;
  }
  const user = await currentUser(supabase, "disableTwoFactor");
  if (!user) {
    return authError("AUTH_FAILED");
  }
  const factor = verifiedTotpFactor(user);
  if (!factor) {
    // Already off.
    return { data: { disabled: true } };
  }

  // A current code first, so an unattended signed-in browser can't turn 2FA off (Question D).
  const { error: verifyError } = await supabase.auth.mfa.challengeAndVerify({
    factorId: factor.id,
    code: parsed.data.code,
  });
  if (verifyError) {
    return codeFailure("disableTwoFactor", verifyError);
  }
  const { error } = await supabase.auth.mfa.unenroll({ factorId: factor.id });
  if (error) {
    logAuthError("disableTwoFactor", error);
    return authError("AUTH_FAILED");
  }
  // New tokens, so the session no longer reflects the removed factor. A failure here is harmless:
  // the old tokens are still valid and the factor is gone either way.
  const { error: refreshError } = await supabase.auth.refreshSession();
  if (refreshError) {
    logAuthError("disableTwoFactor", refreshError);
  }
  return { data: { disabled: true } };
}
